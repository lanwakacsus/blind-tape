import { describe, expect, it } from 'vitest';
import { DAILY, LEVELS, dailyMarket, dailySeed, genMarket, hashSeed, mulberry32, parseCSV } from '../src/engine/market';
import legacy from './fixtures/legacy-engine.json';

describe('genMarket', () => {
  it('is deterministic per seed', () => {
    const a = genMarket(1234, LEVELS[2]);
    const b = genMarket(1234, LEVELS[2]);
    expect(b.bars).toEqual(a.bars);
    expect(b.regimes).toEqual(a.regimes);
  });

  it('gives different tapes for different seeds', () => {
    expect(genMarket(1).closes).not.toEqual(genMarket(2).closes);
  });

  it('builds warm + play bars with coherent OHLC and full regime coverage', () => {
    const m = genMarket(99, { warm: 60, play: 150 });
    expect(m.n).toBe(210);
    expect(m.closes).toHaveLength(210);
    for (const b of m.bars) {
      expect(b.h).toBeGreaterThanOrEqual(Math.max(b.o, b.c));
      expect(b.l).toBeLessThanOrEqual(Math.min(b.o, b.c));
      expect(b.l).toBeGreaterThan(0);
    }
    const spans = m.regimes!;
    expect(spans[0].from).toBe(0);
    expect(spans[spans.length - 1].to).toBe(m.n - 1);
    for (let i = 1; i < spans.length; i++) {
      expect(spans[i].from).toBe(spans[i - 1].to + 1);
      expect(spans[i].k).not.toBe(spans[i - 1].k);
    }
  });

  it('matches markets generated by the original single-file build', () => {
    for (const c of legacy.markets) {
      const m = genMarket(c.seed, c.opts);
      expect(m.n).toBe(c.n);
      const { v: _volume, ...prices } = m.bars[m.n - 1];
      expect(prices).toEqual(c.lastBar);
    }
  });
});

describe('daily seed', () => {
  it('keeps the daily tape identical to the original build', () => {
    for (const [day, ref] of Object.entries(legacy.daily)) {
      expect(dailySeed(day)).toBe(hashSeed('blindtape:' + day));
      expect(dailySeed(day)).toBe(ref.seed);
      const m = dailyMarket(day);
      expect(m.day).toBe(day);
      expect(m.opts).toBe(DAILY);
      expect(m.closes).toEqual(ref.closes);
      expect(m.regimes).toEqual(ref.regimes);
    }
  });
});

describe('mulberry32', () => {
  it('yields floats in [0, 1) and repeats per seed', () => {
    const a = mulberry32(7);
    const b = mulberry32(7);
    for (let i = 0; i < 1000; i++) {
      const x = a();
      expect(x).toBe(b());
      expect(x).toBeGreaterThanOrEqual(0);
      expect(x).toBeLessThan(1);
    }
  });
});

describe('parseCSV', () => {
  const day = (i: number) => new Date(Date.UTC(2024, 0, 1) + i * 864e5).toISOString().slice(0, 10);
  const ohlc = (i: number) => {
    const c = 100 + i;
    return [day(i), c - 0.5, c + 1, c - 1, c].join(',');
  };

  it('reads a header row and maps columns by name in any order', () => {
    const rows = Array.from({ length: 120 }, (_, i) => {
      const c = 100 + i;
      return [c, day(i), c + 1, c - 1, c - 0.5].join(',');
    });
    const m = parseCSV(['Close,Date,High,Low,Open', ...rows].join('\n'), 'spy.csv');
    expect(m.n).toBe(120);
    expect(m.bars[0]).toEqual({ o: 99.5, h: 101, l: 99, c: 100 });
    expect(m.name).toBe('SPY');
    expect(m.csv).toBe(true);
    expect(m.warm).toBe(60);
    expect(m.opts).toEqual({ warm: 60, play: 60 });
  });

  it('finds the price column by name, ignoring case and quotes', () => {
    const rows = Array.from({ length: 100 }, (_, i) => `"${day(i)}";${i};${50 + i}`);
    const m = parseCSV(['"Date";"Volume";"Adj Close"', ...rows].join('\n'));
    expect(m.closes[0]).toBe(50);
  });

  it('puts newest-first files in chronological order', () => {
    const rows = Array.from({ length: 120 }, (_, i) => ohlc(i)).reverse();
    const m = parseCSV(['date,open,high,low,close', ...rows].join('\r\n'));
    expect(m.closes[0]).toBe(100);
    expect(m.closes[m.n - 1]).toBe(219);
  });

  it('accepts a single column of numbers with no header', () => {
    const rows = Array.from({ length: 150 }, (_, i) => String(50 + i * 0.25));
    const m = parseCSV(rows.join('\n'));
    expect(m.n).toBe(150);
    expect(m.closes[0]).toBe(50);
    // With no open/high/low, each bar opens at the previous close.
    expect(m.bars[1]).toEqual({ o: 50, h: 50.25, l: 50, c: 50.25 });
    expect(m.name).toBe('CSV');
  });

  it('keeps only the latest 260 rows', () => {
    const rows = Array.from({ length: 400 }, (_, i) => String(100 + i));
    const m = parseCSV(rows.join('\n'));
    expect(m.n).toBe(260);
    expect(m.closes[0]).toBe(240);
  });

  it('rejects files that are too short or have no prices', () => {
    expect(() => parseCSV('close\n')).toThrow(/fewer than two lines/);
    expect(() => parseCSV(['close', ...Array.from({ length: 50 }, () => '1')].join('\n'))).toThrow(/at least 100 rows of prices; found 50/);
    expect(() => parseCSV('name,ticker\nfoo,bar\nbaz,qux')).toThrow(/no price column/);
  });

  it('gives every bar a volume without changing a single price', () => {
    for (const seed of [1, 42, 4242, 99990]) {
      const m = genMarket(seed);
      expect(m.bars.every((b) => Number.isInteger(b.v) && b.v! > 0)).toBe(true);
      // The same prices come out of the daily tape build, which never knew about volume.
      expect(genMarket(seed).closes).toEqual(m.closes);
    }
  });

  it('runs volume high in a crash, low in chop, and higher on a gap', () => {
    const avg = (kind: string) => {
      const vs: number[] = [];
      for (let seed = 1; seed <= 40; seed++) {
        const m = genMarket(seed * 37);
        for (const s of m.regimes!) if (s.k === kind) for (let t = s.from; t <= s.to; t++) vs.push(m.bars[t].v!);
      }
      return vs.reduce((a, b) => a + b, 0) / vs.length;
    };
    expect(avg('crash')).toBeGreaterThan(avg('chop') * 2);
    expect(avg('melt')).toBeGreaterThan(avg('chop'));
  });
});
